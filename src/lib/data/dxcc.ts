/**
 * Get DXCC entities by continent
 *
 * @param continent - Continent code (NA, SA, EU, AF, AS, OC, AN)
 * @returns Array of entities for that continent
 */
export function getEntitiesByContinent(continent: string): DXCCEntity[] {
  const upperContinent = continent.toUpperCase();
  return DXCC_ENTITIES.filter(
    (e) => !e.deleted && e.continent === upperContinent,
  );
}

/**
 * Get count of current entities by continent
 *
 * @returns Record of continent code to entity count
 */
