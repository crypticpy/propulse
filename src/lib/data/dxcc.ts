/**
 * Get DXCC entity from a callsign prefix
 *
 * @param prefix - Callsign prefix (e.g., "W1", "DL", "JA")
 * @returns DXCC entity or null if not found
 */
export function getDXCCFromPrefix(prefix: string): DXCCEntity | null {
  if (!prefix) return null;

  if (!prefixToDXCC) {
    prefixToDXCC = initPrefixMap();
  }

  const upperPrefix = prefix.toUpperCase();

  // Try exact match first
  if (prefixToDXCC.has(upperPrefix)) {
    return prefixToDXCC.get(upperPrefix)!;
  }

  // Try progressively shorter prefixes
  for (let len = upperPrefix.length - 1; len >= 1; len--) {
    const shortPrefix = upperPrefix.slice(0, len);
    if (prefixToDXCC.has(shortPrefix)) {
      return prefixToDXCC.get(shortPrefix)!;
    }
  }

  return null;
}

/**
 * Extract prefix from a full callsign
 *
 * @param callsign - Full callsign (e.g., "W1ABC", "DL2XYZ", "JA1ABC/P")
 * @returns Extracted prefix suitable for DXCC lookup
 */
function extractPrefix(callsign: string): string {
  if (!callsign) return "";

  // Handle portable/mobile operations with prefix (e.g., "DL/W1ABC")
  const parts = callsign.toUpperCase().split("/");

  // If there's a prefix modifier, use it for DXCC determination
  if (parts.length > 1) {
    const firstPart = parts[0];
    const secondPart = parts[1];

    // Common suffixes to ignore
    const suffixes = [
      "P",
      "M",
      "MM",
      "AM",
      "QRP",
      "A",
      "B",
      "1",
      "2",
      "3",
      "4",
      "5",
      "6",
      "7",
      "8",
      "9",
      "0",
    ];

    // If second part is a suffix, use first part
    if (suffixes.includes(secondPart) || secondPart.length <= 2) {
      return extractBasePrefix(firstPart);
    }

    // If first part looks like a country prefix and second part is a callsign
    if (firstPart.length <= 4 && secondPart.length > 4) {
      return firstPart;
    }

    // Default to first part
    return extractBasePrefix(firstPart);
  }

  return extractBasePrefix(parts[0]);
}

/**
 * Extract base prefix from a callsign without modifiers
 */
function extractBasePrefix(call: string): string {
  // Handle special prefixes with numbers (e.g., HB9, EA6, KP4, VK9X)
  const specialPrefixMatch = call.match(/^([A-Z]{1,2}\d[A-Z]?)/);
  if (specialPrefixMatch) {
    return specialPrefixMatch[1];
  }

  // Standard format: 1-2 letters, then a number
  const standardMatch = call.match(/^([A-Z]{1,2})(\d)?/);
  if (standardMatch) {
    return standardMatch[1] + (standardMatch[2] || "");
  }

  // Handle numeric prefixes like 3DA, 5B, 9M
  const numericPrefixMatch = call.match(/^(\d[A-Z]{1,2})/);
  if (numericPrefixMatch) {
    return numericPrefixMatch[1];
  }

  // Fallback: return first 2 characters
  return call.slice(0, 2);
}

/**
 * Get DXCC entity from a full callsign
 *
 * @param callsign - Full callsign (e.g., "W1ABC", "DL2XYZ/P", "DL/W1ABC")
 * @returns DXCC entity or null if not found
 */
export function getDXCCFromCallsign(callsign: string): DXCCEntity | null {
  const prefix = extractPrefix(callsign);
  return getDXCCFromPrefix(prefix);
}

