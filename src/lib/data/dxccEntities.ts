// ─── Prefix Lookup Table ────────────────────────────────────────────────────

/**
 * Build a lookup table mapping callsign prefixes to DXCC entities.
 * For longest-prefix-match, we try progressively shorter prefixes.
 */
const prefixToEntity = new Map<string, DXCCEntity>();

for (const entity of DXCC_ENTITIES) {
  prefixToEntity.set(entity.prefix.toUpperCase(), entity);
}

// ─── Public API ─────────────────────────────────────────────────────────────

/**
 * Look up a DXCC entity from a callsign using longest-prefix-match.
 *
 * Strips suffixes (e.g., /P, /M, /QRP) and tries progressively shorter
 * prefixes until a match is found in the entity database.
 */
export function lookupEntity(callsign: string): DXCCLookupResult | null {
  if (!callsign) return null;

  // Strip suffixes
  const baseCall = callsign.split("/")[0].toUpperCase();
  if (!baseCall) return null;

  // Try progressively shorter prefixes (longest match wins)
  for (let len = Math.min(baseCall.length, 5); len >= 1; len--) {
    const prefix = baseCall.slice(0, len);
    const entity = prefixToEntity.get(prefix);
    if (entity) {
      return { entity, matchedPrefix: prefix };
    }
  }

  // Try numeric-prefixed callsigns (e.g., 5Z, 9M, 3B)
  const numericMatch = baseCall.match(/^(\d[A-Z]{1,2})/);
  if (numericMatch) {
    const prefix = numericMatch[1];
    const entity = prefixToEntity.get(prefix);
    if (entity) {
      return { entity, matchedPrefix: prefix };
    }
  }

  return null;
}

/**
 * Get a DXCC entity by its DXCC ID number.
 */
export function getEntityById(id: number): DXCCEntity | undefined {
  return DXCC_ENTITIES.find((e) => e.id === id);
}

/**
 * Get all active DXCC entities.
 */
export function getActiveEntities(): DXCCEntity[] {
  return DXCC_ENTITIES.filter((e) => e.isActive);
}

/**
 * Get all entities for a given continent.
 */
export function getEntitiesByContinent(continent: string): DXCCEntity[] {
  return DXCC_ENTITIES.filter(
    (e) => e.continent === continent.toUpperCase() && e.isActive,
  );
}

/**
 * Get the total count of active DXCC entities.
 */
export function getActiveDXCCCount(): number {
  return DXCC_ENTITIES.filter((e) => e.isActive).length;
}
