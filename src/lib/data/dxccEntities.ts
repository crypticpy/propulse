/**
 * DXCC Entity Database
 *
 * Comprehensive database of ~340 DXCC (DX Century Club) entities with:
 * - Entity name, prefix, and continent code
 * - Geographic coordinates (lat/lon)
 * - CQ and ITU zone numbers
 * - Callsign prefix patterns for longest-prefix-match lookup
 *
 * Data sourced from ARRL DXCC list and Club Log prefix database.
 */

// ─── Types ──────────────────────────────────────────────────────────────────

export interface DXCCEntity {
  /** DXCC entity number (ARRL numbering) */
  id: number;
  /** Entity name as per ARRL DXCC list */
  name: string;
  /** Primary callsign prefix */
  prefix: string;
  /** Continent code: NA, SA, EU, AF, AS, OC, AN */
  continent: string;
  /** CQ zone number */
  cqZone: number;
  /** ITU zone number */
  ituZone: number;
  /** Reference latitude in degrees */
  lat: number;
  /** Reference longitude in degrees */
  lon: number;
  /** Whether this entity is currently on the DXCC active list */
  isActive: boolean;
}

export interface DXCCLookupResult {
  entity: DXCCEntity;
  matchedPrefix: string;
}

