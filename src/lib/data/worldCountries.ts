/**
 * World Countries Boundary Data
 *
 * Provides simplified country boundary polygons and centroid positions for
 * rendering country outlines and labels on both the 3D globe and 2D flat map.
 *
 * Border coordinates are simplified to 10-50 points per polygon for efficient
 * rendering at moderate zoom levels. Coordinates use [lat, lon] tuples.
 *
 * Area values are approximate (nearest 1000 km²) and used to determine
 * which labels show at which zoom levels.
 */

export interface CountryData {
  name: string;
  iso: string;
  centroidLat: number;
  centroidLon: number;
  area: number;
  borders: [number, number][][];
}

