// ============================================================================
// Gray Code Map
// ============================================================================

/**
 * 3-bit Gray code map for FT8.
 *
 * Maps a 3-bit data value (0-7) to the corresponding FSK-8 tone index.
 * Adjacent tones differ by one bit in the Gray code representation,
 * minimizing errors when a symbol is decoded to an adjacent tone.
 */
export const FT8_GRAY_MAP: readonly number[] = [0, 1, 3, 2, 5, 6, 4, 7];

/**
 * 2-bit Gray code map for FT4.
 */
export const FT4_GRAY_MAP: readonly number[] = [0, 1, 3, 2];

