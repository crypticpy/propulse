/** Number of data bits (77 message + 14 CRC). */
export const FTX_LDPC_K = 91;

/** Number of parity check bits. */
export const FTX_LDPC_M = 83;

/** Total coded bits (K + M). */
export const FTX_LDPC_N = 174;

/** Bytes per generator row: ceil(91 / 8) = 12. */
export const FTX_LDPC_K_BYTES = 12;

// ============================================================================
// CRC-14
// ============================================================================

/**
 * CRC-14 polynomial used by FT8/FT4.
 *
 * This is the polynomial without the leading x^14 term:
 *   x^13 + x^10 + x^8 + x^6 + x^4 + x^2 + x + 1
 *
 * Source: WSJT-X / ft8_lib constants.h — FT8_CRC_POLYNOMIAL
 */
export const FT8_CRC_POLYNOMIAL = 0x2757;

/** CRC bit width. */
export const FT8_CRC_WIDTH = 14;

// ============================================================================
// Costas Synchronization Array
// ============================================================================

/**
 * 7-symbol Costas array inserted at three positions in the FT8 symbol sequence.
 *
 * Positions: 0-6, 36-42, 72-78 (three groups of 7 within the 79-symbol frame).
 */
export const FT8_COSTAS: readonly number[] = [3, 1, 4, 0, 6, 5, 2];

/**
 * 4-symbol Costas array for FT4.
 *
 * Positions: 0-3, 33-36, 66-69, 99-102 (four groups within the 105-symbol frame).
 */
